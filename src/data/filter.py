def norm_license(value: Any) -> str:
    # Normalize SPDX license strings or lists into lowercase semicolon-separated tokens.
    if value is None:
        return ""
    if isinstance(value, list):
        return ";".join(norm_license(v) for v in value if v is not None)
    return str(value).strip().lower().replace("license:", "").strip()


def reject_path(path_value: Any) -> bool:
    # Reject vendored, minified, lockfile, or non-Batch-1 file extensions.
    if not isinstance(path_value, str) or not path_value.strip():
        return False
    path = path_value.replace("\\", "/").strip().lower()
    parts = {p for p in path.split("/") if p}
    if parts.intersection(REJECTED_DIRS):
        return True
    if path.endswith(REJECTED_SUFFIXES):
        return True
    filename = path.rsplit("/", 1)[-1]
    if "." in filename:
        ext = "." + filename.rsplit(".", 1)[-1]
        if ext not in BATCH1_ALLOWED_EXTENSIONS:
            return True
    return False


def classify_batch1_ecosystem(record: dict[str, Any], text: str) -> list[str]:
    # Classify a source record into Batch 1 tags (javascript, typescript, nodejs, expressjs, nestjs).
    tags: set[str] = set()
    low = text.lower()
    path = str(record.get("path") or "").lower()
    lang = str(record.get("language") or record.get("lang") or record.get("stack") or "").lower()
    framework = str(record.get("framework") or "").lower()

    if (
        "@nestjs/" in low
        or "@controller(" in low
        or "@injectable(" in low
        or "@module(" in low
        or "nestfactory" in low
        or "nestjs" in lang
        or "nestjs" in framework
    ):
        tags.add("nestjs")
        tags.add("typescript")
        tags.add("nodejs")

    if (
        "from 'express'" in low
        or 'from "express"' in low
        or "require('express')" in low
        or 'require("express")' in low
        or "express.router(" in low
        or "app.use(" in low
        or "req, res, next" in low
        or "req: request, res: response" in low
        or "express" in lang
        or "express" in framework
    ):
        tags.add("expressjs")
        tags.add("nodejs")

    if (
        "node:" in low
        or "require('fs" in low
        or 'require("fs' in low
        or "require('http" in low
        or 'require("http' in low
        or "require('crypto" in low
        or "require('path" in low
        or "process.env" in low
        or "buffer.from" in low
        or "eventemitter" in low
        or "module.exports" in low
        or "node" in lang
        or "node" in framework
    ):
        tags.add("nodejs")

    is_ts = (
        path.endswith((".ts", ".mts", ".cts", ".tsx"))
        or lang in {"typescript", "ts", "tsx", "nestjs", "nest", "nest.js"}
        or "interface " in low
        or "readonly " in low
        or ": string" in low
        or ": number" in low
        or ": boolean" in low
        or ": promise<" in low
        or "record<string" in low
    )
    if is_ts:
        tags.add("typescript")
    else:
        tags.add("javascript")

    return sorted(tags)


def is_batch1_compatible(record: dict[str, Any], text: str) -> bool:
    # Verify metadata and code syntax belong to Batch 1 (JS/TS/Node/Express/NestJS).
    for meta_key in ("language", "lang", "stack", "framework"):
        val = record.get(meta_key)
        if isinstance(val, str) and val.strip() and val.strip().lower() not in BATCH1_ALLOWED_LANGUAGES:
            return False
    low = text.lower()
    return any(marker in low for marker in JS_TS_SYNTAX_MARKERS)


def looks_like_code(text: str, min_chars: int = 40) -> bool:
    # Filter out short fragments, binary data, generated bundles, and benchmark leakage.
    stripped = text.strip()
    if len(stripped) < min_chars or len(stripped) > 500_000:
        return False
    if "\x00" in stripped:
        return False
    low = stripped.lower()
    if any(marker in low for marker in GENERATED_MARKERS):
        return False
    if any(marker in low for marker in BENCHMARK_LEAKAGE_MARKERS):
        return False
    lines = stripped.splitlines()
    if not lines:
        return False
    max_line_len = max(len(line) for line in lines)
    avg_line_len = len(stripped) / max(1, len(lines))
    return not (max_line_len > 1000 or avg_line_len > 200)


def contains_secret(text: str) -> bool:
    # Screen source text against credential, private key, and token regex patterns.
    return any(pattern.search(text) for pattern in SECRET_PATTERNS)
